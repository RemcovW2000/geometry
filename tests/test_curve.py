import numpy as np
import pytest

from geometry import InterpolatedLine, Point
from geometry.primitives import Plane, Vector


@pytest.fixture
def points() -> list[Point]:
    return [Point(0, 0, 0), Point(1, 0, 0), Point(2, 0, 0)]


@pytest.fixture
def interpolated_curve(points: list[Point]) -> InterpolatedLine:
    return InterpolatedLine(points=points)


@pytest.mark.parametrize(
    "u, expected_point",
    [
        (0, Point(0, 0, 0)),
        (0.5, Point(1, 0, 0)),
        (1, Point(2, 0, 0)),
    ],
)
def test_point_at_param(
    u: float, expected_point: Point, interpolated_curve: InterpolatedLine
) -> None:
    assert interpolated_curve.point_at_parameter(u).is_at_point(expected_point)
    assert np.isclose(interpolated_curve.parameter_at_point(expected_point), u, atol=1e-5)


@pytest.fixture
def plane() -> Plane:
    return Plane(point=Point(1, 0, 0), normal=Vector(1, 0, 0))


def test_plane_intersection(interpolated_curve: InterpolatedLine, plane: Plane) -> None:
    intersections = interpolated_curve.plane_intersection_point(plane)
    assert len(intersections) == 1
    pt = intersections[0]
    assert pt.is_at_point(Point(1, 0, 0))


